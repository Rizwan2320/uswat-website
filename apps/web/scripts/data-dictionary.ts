/**
 * Generates docs/data-dictionary.md from the CMS configuration, so the dictionary cannot drift from the schema.
 * Usage (from apps/web): pnpm dictionary:build
 * It reads configuration only; it needs no database connection beyond what loading the config requires.
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'

type F = Record<string, unknown> & { name?: string; type: string; fields?: F[]; tabs?: { fields: F[] }[] }
type Row = { name: string; type: string; required: boolean; localized: boolean; note: string }

const label = (v: unknown): string => (typeof v === 'string' ? v : v && typeof v === 'object' ? String(Object.values(v)[0] ?? '') : '')
const clean = (s: string) => s.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim()

function describe(f: F): string {
  const bits: string[] = []
  if (f.relationTo) bits.push(`-> ${Array.isArray(f.relationTo) ? f.relationTo.join(', ') : String(f.relationTo)}${f.hasMany ? ' (many)' : ''}`)
  if (Array.isArray(f.options)) bits.push(`one of: ${(f.options as ({ value: string } | string)[]).map((o) => (typeof o === 'string' ? o : o.value)).join(', ')}`)
  if (f.defaultValue !== undefined && typeof f.defaultValue !== 'function') bits.push(`default: ${JSON.stringify(f.defaultValue)}`)
  const admin = f.admin as { description?: unknown; readOnly?: boolean } | undefined
  if (admin?.readOnly) bits.push('set by the system')
  const d = label(admin?.description)
  if (d) bits.push(d)
  return clean(bits.join('. '))
}

function walk(fields: F[], prefix: string, out: Row[]) {
  for (const f of fields) {
    if (f.type === 'row' || f.type === 'collapsible') walk(f.fields ?? [], prefix, out)
    else if (f.type === 'tabs') for (const t of f.tabs ?? []) walk(t.fields, prefix, out)
    else if (!f.name || f.name === 'governance') continue
    else if (f.type === 'group') walk(f.fields ?? [], `${prefix}${f.name}.`, out)
    else if (f.type === 'array' || f.type === 'blocks') {
      out.push({ name: `${prefix}${f.name}`, type: f.type, required: !!f.required, localized: !!f.localized, note: describe(f) })
      if (f.type === 'array') walk(f.fields ?? [], `${prefix}${f.name}[].`, out)
    } else if (f.type !== 'ui' && !/^(generateSlug|_status|id|createdAt|updatedAt)$/.test(f.name)) {
      out.push({ name: `${prefix}${f.name}`, type: f.type, required: !!f.required, localized: !!f.localized, note: describe(f) })
    }
  }
}

async function main() {
  const config = await (await import('../src/payload.config')).default
  const { governanceFields } = await import('../src/governance/fields')
  const lines: string[] = [
    '# Data dictionary',
    '',
    'Generated by `pnpm dictionary:build` from the CMS configuration. Do not edit by hand: change the collection and run it again.',
    '',
    '## Rules that hold for every record below',
    '',
    '- A collection marked Governed below has the `governance` group (next section): records start as drafts and nothing is public until it is published. Media, Categories, Users, Audit logs, Redirects, Forms, Form submissions and Search results are not governed.',
    '- A fact needs `governance.source` (a URL or a named document) and, once a reviewer verifies it, `verifiedAt`. Only a reviewer can verify; an import or a job cannot.',
    '- Invented data is labelled Sample: its source is on the host `sample.invalid` and its name starts with "Sample". Public pages show a Sample label for it.',
    '- Personal fields (a person\'s email and photo) have their own visibility, Hidden by default. Contact details found in imported text are removed and counted, not stored.',
    '',
    '## Governance group (on every governed collection)',
    '',
    '| Field | Type | Notes |',
    '| --- | --- | --- |',
  ]
  for (const f of governanceFields as unknown as F[]) lines.push(`| \`${f.name}\` | ${f.type} | ${describe(f) || label(f.label)} |`)
  lines.push('')
  const shown = config.collections.filter((c) => !c.slug.startsWith('payload-'))
  for (const c of shown) {
    const rows: Row[] = []
    walk(c.fields as unknown as F[], '', rows)
    const governed = (c.fields as unknown as F[]).some((f) => f.name === 'governance')
    const admin = c.admin as { group?: unknown } | undefined
    lines.push(`## ${label(c.labels?.plural) || c.slug} (\`${c.slug}\`)`, '')
    lines.push(`Group in the admin: ${label(admin?.group) || 'none'}. ${governed ? 'Governed.' : 'Not governed.'} ${c.versions && typeof c.versions === 'object' && 'drafts' in c.versions && c.versions.drafts ? 'Has drafts.' : 'No drafts.'}`, '')
    lines.push('| Field | Type | Required | Translated | Notes |', '| --- | --- | --- | --- | --- |')
    for (const r of rows) lines.push(`| \`${r.name}\` | ${r.type} | ${r.required ? 'yes' : ''} | ${r.localized ? 'yes' : ''} | ${r.note} |`)
    lines.push('')
  }
  const out = path.resolve(process.cwd(), '../../docs/data-dictionary.md')
  writeFileSync(out, lines.join('\n'))
  console.log(`wrote ${shown.length} collections to docs/data-dictionary.md`)
}

main().then(() => process.exit(0), (e) => {
  console.error(e instanceof Error ? e.message : e)
  process.exit(1)
})
